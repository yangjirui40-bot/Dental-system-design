CREATE TABLE invoice_line (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  invoice_revision_id bigint NOT NULL,
  line_no integer NOT NULL,
  treatment_revision_id bigint NOT NULL,
  treatment_name_snapshot varchar(100) NOT NULL,
  unit_name_snapshot varchar(40) NOT NULL,
  quantity_snapshot numeric(10,3) NOT NULL,
  unit_price_snapshot numeric(12,2) NOT NULL,
  subtotal numeric(14,2) GENERATED ALWAYS AS (round(quantity_snapshot * unit_price_snapshot, 2)) STORED NOT NULL,

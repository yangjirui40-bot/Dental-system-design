  completed_by bigint,
  completed_at timestamptz,
  pause_or_end_reason text,
  row_version integer NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (plan_id, phase_no),
  CHECK (phase_no > 0),
  CHECK (row_version > 0),
  CHECK (progress_outcome IN ('waiting','ready','booked','completed','paused','terminated'))
);

CREATE TABLE phase_specification (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  plan_revision_id bigint NOT NULL,
  phase_id bigint NOT NULL,
  phase_title varchar(100) NOT NULL,
  clinical_condition text NOT NULL,
  earliest_at timestamptz,
  latest_at timestamptz,
  suggested_clinic_id bigint,
  responsible_clinic_id bigint NOT NULL,
  estimated_fee numeric(14,2),
  PRIMARY KEY (id),
  UNIQUE (plan_revision_id, phase_id),
  UNIQUE (id, phase_id),
  CHECK (latest_at IS NULL OR earliest_at IS NULL OR latest_at >= earliest_at),
  CHECK (estimated_fee IS NULL OR estimated_fee >= 0)
);

CREATE TABLE phase_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  phase_specification_id bigint NOT NULL,
  standard_id bigint NOT NULL,
  site_description varchar(160),
  planned_quantity numeric(10,3) NOT NULL,
  PRIMARY KEY (id),
  CHECK (planned_quantity > 0)
);

CREATE TABLE phase_dependency (
  plan_revision_id bigint NOT NULL,
  predecessor_phase_id bigint NOT NULL,
  successor_phase_id bigint NOT NULL,
  PRIMARY KEY (plan_revision_id, predecessor_phase_id, successor_phase_id),
  CHECK (predecessor_phase_id <> successor_phase_id)
);

CREATE TABLE appointment (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  appointment_no varchar(40) NOT NULL UNIQUE,
  patient_id bigint NOT NULL,
  dentist_id bigint NOT NULL,
  clinic_id bigint NOT NULL,
  duty_id bigint NOT NULL,
  previous_appointment_id bigint UNIQUE,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  resolution varchar(24) NOT NULL,
  has_attended boolean GENERATED ALWAYS AS ((resolution = 'seen')) STORED NOT NULL,
  presenting_request text,
  special_needs text,
  created_by bigint,
  created_at timestamptz NOT NULL,
  row_version integer NOT NULL,
  operatory_id bigint NOT NULL,
  request_channel varchar(24) NOT NULL,
  created_account_id bigint NOT NULL,
  PRIMARY KEY (id),
  CHECK (ends_at > starts_at),
  CHECK (row_version > 0),
  CHECK (previous_appointment_id IS NULL OR previous_appointment_id <> id),
  CHECK (resolution IN ('booked','arrived','seen','cancelled','rescheduled','unfulfilled','no_show','left_unseen')),
  CHECK (request_channel IN ('patient_portal','representative_portal','reception'))
);


  email varchar(160) NOT NULL,
  employed_from date NOT NULL,
  employed_to date,
  row_version integer NOT NULL,
  PRIMARY KEY (id),
  CHECK (employed_to IS NULL OR employed_to >= employed_from),
  CHECK (row_version > 0)
);

CREATE TABLE dentist (

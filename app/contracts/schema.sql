  stopped_at timestamptz,
  stop_reason text,
  row_version integer NOT NULL,
  calendar_id bigint NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (id, dentist_id, clinic_id),
  CHECK (ends_at > starts_at),
  CHECK (publication_state IN ('draft','pending_coordination','published','stopped','superseded')),
  CHECK (row_version > 0)

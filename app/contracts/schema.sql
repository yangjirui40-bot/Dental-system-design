  UNIQUE (invoice_revision_id, line_no),
  UNIQUE (invoice_revision_id, treatment_revision_id),
  CHECK (line_no > 0),
  CHECK (quantity_snapshot > 0),
  CHECK (unit_price_snapshot >= 0)

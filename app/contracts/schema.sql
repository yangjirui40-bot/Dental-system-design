-- ADC physical storage mapping. PostgreSQL 18; UTF-8; application timezone Asia/Shanghai.

-- Structural DDL only: cross-aggregate transaction guards are specified in the design document.

-- These guards require application/constraint-trigger implementation; this file alone is not a complete application.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE patient (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  account_no varchar(40) NOT NULL UNIQUE,
  full_name varchar(100) NOT NULL,
  birth_date date NOT NULL,
  sex_code varchar(40),
  billing_address varchar(160) NOT NULL,
  phone varchar(40) NOT NULL,
  email varchar(160),
  allergy_declaration varchar(24) NOT NULL,
  row_version integer NOT NULL,
  created_at timestamptz NOT NULL,
  PRIMARY KEY (id),
  CHECK (allergy_declaration IN ('unknown','denied','reported')),
  CHECK (row_version > 0)
);

CREATE TABLE patient_contact (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  patient_id bigint NOT NULL,
  full_name varchar(100) NOT NULL,
  phone varchar(40) NOT NULL,
  relationship varchar(160) NOT NULL,
  contact_purpose varchar(24) NOT NULL,
  recorded_by bigint,
  recorded_at timestamptz NOT NULL,
  recorded_account_id bigint NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (id, patient_id),
  CHECK (contact_purpose IN ('emergency','guardian','agent'))
);

CREATE TABLE patient_authority (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  patient_id bigint NOT NULL,
  contact_id bigint NOT NULL,
  permission_scope varchar(24) NOT NULL,
  evidence_reference varchar(160) NOT NULL,
  valid_from timestamptz NOT NULL,
  valid_to timestamptz,
  verified_by bigint NOT NULL,
  verified_at timestamptz NOT NULL,
  revoked_at timestamptz,
  authorized_account_id bigint,
  PRIMARY KEY (id),
  CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE TABLE allergy_substance (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  substance_name varchar(100) NOT NULL UNIQUE,
  substance_category varchar(40) NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE patient_allergy (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  patient_id bigint NOT NULL,
  substance_id bigint NOT NULL,
  first_reported_at timestamptz NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (patient_id, substance_id)
);

CREATE TABLE allergy_revision (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  allergy_id bigint NOT NULL,
  revision_no integer NOT NULL,
  replaces_id bigint UNIQUE,
  reaction_description text,
  reporter_name varchar(100) NOT NULL,
  report_source varchar(160) NOT NULL,
  verification_result varchar(24) NOT NULL,
  verified_by bigint,
  verified_at timestamptz,
  correction_reason text,
  recorded_by bigint,
  recorded_at timestamptz NOT NULL,
  recorded_account_id bigint NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (allergy_id, revision_no),
  CHECK (revision_no > 0),
  CHECK (replaces_id IS NULL OR replaces_id <> id),
  CHECK (verification_result IN ('reported','verified','refuted')),
  CHECK (verification_result = 'reported' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL))
);

CREATE TABLE employee (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  employee_no varchar(40) NOT NULL UNIQUE,
  full_name varchar(100) NOT NULL,
  birth_date date NOT NULL,
  home_address varchar(160) NOT NULL,

CREATE TABLE treatment_standard (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  treatment_id bigint NOT NULL,
  revision_no integer NOT NULL,
  treatment_name varchar(100) NOT NULL,
  unit_name varchar(40) NOT NULL,
  quantity_scale integer NOT NULL,
  unit_price numeric(12,2) NOT NULL,
  site_requirement varchar(160) NOT NULL,
  valid_from timestamptz NOT NULL,
  valid_to timestamptz,
  approval_state varchar(24) NOT NULL,
  approved_by bigint,
  approved_at timestamptz,
  duration_minutes integer NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (treatment_id, revision_no),
  CHECK (revision_no > 0),
  CHECK (unit_price >= 0),
  CHECK (quantity_scale BETWEEN 0 AND 3),
  CHECK (valid_to IS NULL OR valid_to > valid_from),
  CHECK (approval_state IN ('draft','approved','rejected','retired')),
  CHECK (duration_minutes > 0)
);

CREATE TABLE standard_qualification (

-- Authentication extension requested on 2026-11-12; supplied public business DDL is unchanged.
CREATE SCHEMA IF NOT EXISTS adc_auth;
CREATE TABLE IF NOT EXISTS adc_auth.wechat_identity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES public.user_account(id),
  appid varchar(32) NOT NULL,
  subject_hash char(64) NOT NULL,
  created_at timestamptz NOT NULL,
  last_used_at timestamptz,
  revoked_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_wechat_account_active
  ON adc_auth.wechat_identity(account_id, appid) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_wechat_subject_active
  ON adc_auth.wechat_identity(appid, subject_hash) WHERE revoked_at IS NULL;
ALTER TABLE adc_auth.wechat_identity ADD COLUMN IF NOT EXISTS revoked_by bigint REFERENCES public.user_account(id);
ALTER TABLE adc_auth.wechat_identity ADD COLUMN IF NOT EXISTS revocation_basis varchar(160);
